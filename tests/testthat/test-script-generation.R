# The R script the app generates must parse, run on its own, and give the app's
# results exactly. It is built from structured records of what the user did, so
# these tests drive a session through shiny::testServer() and then run what
# comes out.

q <- function(expr) suppressWarnings(suppressMessages(expr))
DIMS5 <- c("mo", "sc", "ua", "pd", "ad")

# A session: load, map, validate, two value columns, five analyses.
run_session <- function(e, source = c("example", "csv"), path = NULL) {
  source <- match.arg(source)
  rv <- shiny::reactiveValues(raw_data = NULL, mapping = NULL,
                              processed_data = NULL, results = list(),
                              load_example = 0L, value_cols = character(0L),
                              steps = list())

  q(shiny::testServer(e$mod_data_server, args = list(rv = rv), {
    if (source == "example") {
      session$setInputs(use_example = 1)
    } else {
      session$setInputs(file = list(name = basename(path), datapath = path))
    }
    session$setInputs(version = "3L", col_mo = "mo", col_sc = "sc",
                      col_ua = "ua", col_pd = "pd", col_ad = "ad",
                      col_fu = "time", col_groupvar = "procedure",
                      col_id = "id", col_vas = "vas", col_age = "ageband",
                      col_sex = "gender", col_utility = "",
                      fu_order = c("Pre-op", "Post-op"), confirm = 1)
  }))
  q(shiny::testServer(e$mod_validation_server, args = list(rv = rv), {
    session$setInputs(proceed = 1)
  }))
  q(shiny::testServer(e$mod_values_server, args = list(rv = rv), {
    session$setInputs(method = "direct", country = "GB",
                      col_name = "utility", add = 1)
    session$setInputs(method = "uk", age_col = "ageband", age_kind = "bands",
                      sex_col = "gender", male_value = "Male",
                      col_name = "eq5d_uk_5L", add = 1)
  }))
  for (o in list(c("profile", "111"), c("vas", "21"),
                 c("values", "31"), c("profile", "121fig"),
                 c("profile", "141"))) {
    q(shiny::testServer(e$mod_analysis_server, args = list(rv = rv), {
      session$setInputs(component = o[1])
      session$setInputs(output = o[2])
      if (o[2] == "31") session$setInputs(utility_col = "utility")
      session$setInputs(run = 1)
    }))
  }
  shiny::isolate(list(steps = rv$steps, results = rv$results,
                      data = rv$processed_data))
}

generate <- function(session)
  eq5dsuite:::script_from_session(session$steps, session$results)

# Run a generated script in a clean environment.
run_script <- function(lines, data_path = NULL) {
  f <- tempfile(fileext = ".R")
  if (!is.null(data_path))
    lines <- fill_data_path(lines, data_path)
  writeLines(lines, f)
  env <- new.env(parent = globalenv())
  # The script prints its plots; send them nowhere rather than leaving an
  # Rplots.pdf behind in the check directory.
  grDevices::pdf(NULL)
  on.exit(grDevices::dev.off(), add = TRUE)
  q(sys.source(f, envir = env))
  env
}

