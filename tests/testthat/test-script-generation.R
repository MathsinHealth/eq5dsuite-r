# The script's validation section, on its own, so it can be run against data
# chosen to trip a particular check. Everything between the two section
# headings; `lines` is the generated script.
validation_block <- function(lines) {
  at <- grep("^# [0-9]+\\. ", lines)
  from <- grep("^# 2\\. Validation", lines)
  to <- at[at > from][1L]
  lines[seq(from + 1L, (if (is.na(to)) length(lines) + 1L else to) - 1L)]
}

# Run that block over `df` and say what it signalled: "error", "warning" or
# "clean". The script checks the data it is given, so the block needs only
# `analysis_data` and the mapping it was generated from.
validation_outcome <- function(lines, df, mapping) {
  env <- new.env(parent = globalenv())
  # The script's preamble first: it defines parse_number() and
  # parse_levels(), which the checks use.
  pre <- lines[seq_len(grep("^# 1\\. Load data", lines)[1L] - 1L)]
  eval(parse(text = paste(pre, collapse = "\n")), envir = env)
  env$analysis_data <- df
  env$mapping <- mapping
  code <- parse(text = paste(validation_block(lines), collapse = "\n"))
  warned <- FALSE
  out <- tryCatch(
    withCallingHandlers(
      { suppressMessages(for (ex in code) eval(ex, envir = env)); "clean" },
      warning = function(w) { warned <<- TRUE; invokeRestart("muffleWarning") }),
    error = function(e) "error")
  if (identical(out, "error")) "error" else if (warned) "warning" else "clean"
}

test_that("the script's checks signal what eq5d_validate signals", {
  skip_unless_app()
  e <- app_env()
  session <- run_session(e)
  lines <- generate(session)
  mapping <- eq5dsuite:::.step_of(session$steps, "map")$mapping
  df <- session$data

  # example_data carries the 9 and 999 missing codes, which are out of the
  # dimensions' range, so there is something to warn about and nothing to stop
  # for. A naive stopifnot() would halt the script here, where the app went on.
  found <- q(eq5dsuite:::eq5d_validate(df, mapping, quiet = TRUE))
  expect_true(any(found$type == "warning"))
  expect_false(any(found$type == "error"))
  expect_identical(validation_outcome(lines, df, mapping), "warning")

  # A missing dimension column is the one finding that stops the script.
  gone <- df[, setdiff(names(df), "mo"), drop = FALSE]
  missing_found <- q(eq5dsuite:::eq5d_validate(gone, mapping, quiet = TRUE))
  expect_true(any(missing_found$type == "error"))
  expect_identical(validation_outcome(lines, gone, mapping), "error")

  # Clean data pass without a warning: levels in range, EQ VAS in range, and
  # one row per patient and timepoint.
  ok <- data.frame(
    mo = 1L, sc = 2L, ua = 1L, pd = 3L, ad = 1L,
    id = 1:4, fu = rep(c("Pre-op", "Post-op"), 2L), vas = c(50, 60, 70, 80))
  expect_identical(validation_outcome(lines, ok, mapping), "clean")
})

