  expect_true(any(grepl("check.names = FALSE", lines, fixed = TRUE)))

  env <- run_script(lines, data_path = path)
  expect_identical(env$analysis_data$utility, session$data$utility)
  expect_equal(env$profile_level_summary, session$results[[1L]]$data)
