test_that("it has a header and the four sections, in order", {
  skip_unless_app()
  lines <- generate(run_session(app_env()))
  txt <- paste(lines, collapse = "\n")

  expect_match(txt, "Generated by the eq5dsuite Shiny app on \\d{4}-\\d{2}-\\d{2}")
  expect_match(txt, "eq5dsuite 2\\.", fixed = FALSE)
  expect_match(txt, R.version.string, fixed = TRUE)
  expect_match(txt, "library(eq5dsuite)", fixed = TRUE)

  at <- vapply(c("# 1. Load data", "# 2. Validation",
                 "# 3. EQ-5D value calculation", "# 4. Analysis"),
               function(h) grep(h, lines, fixed = TRUE)[1], integer(1L))
  expect_false(anyNA(at))
  expect_identical(at, sort(at))
})

test_that("it uses only exported functions, and defines its own helpers", {
  skip_unless_app()
  lines <- generate(run_session(app_env()))
  expect_false(any(grepl(":::", lines, fixed = TRUE)))

  pd <- utils::getParseData(parse(text = paste(lines, collapse = "\n"),
                                  keep.source = TRUE))
  called <- unique(pd$text[pd$token == "SYMBOL_FUNCTION_CALL"])

  # Every eq5dsuite function it calls is exported. The app's own supporting
  # functions are internal, so this is what makes the script write their work
  # out instead of calling them: naming one here would fail this.
  ours <- grep("^eq5d|^eqxw|^eqvs|^make_|^toEQ5D", called, value = TRUE)
  expect_true(all(ours %in% getNamespaceExports("eq5dsuite")),
              info = paste(setdiff(ours, getNamespaceExports("eq5dsuite")),
                           collapse = ", "))

  # The one helper it writes out for itself is defined before it is used.
  # band_midpoint() is gone: the age bands are now resolved when the script
  # is generated and written out as a lookup, so the script holds the ages
  # the app actually used rather than a second copy of the parser.
  defined <- grep("^format_eq5d_table <- function", lines)
  expect_length(defined, 1L)
  expect_true(all(grep("\\bformat_eq5d_table\\(", lines) > defined))
  expect_false(any(grepl("band_midpoint", lines, fixed = TRUE)))
  # The lookup is there instead, and its labels are quoted so it parses.
  expect_true(any(grepl("age_for_band <- c(", lines, fixed = TRUE)))
})

