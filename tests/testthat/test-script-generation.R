test_that("the script follows the Results order and drops what was removed", {
  skip_unless_app()
  e <- app_env()
  session <- run_session(e)

  rv <- shiny::reactiveValues(results = session$results)
  shiny::isolate({
    e$move_result(rv, session$results[[4L]]$id, -1L)
    e$move_result(rv, session$results[[4L]]$id, -1L)
    e$remove_result(rv, session$results[[2L]]$id)
  })
  kept <- shiny::isolate(rv$results)

  lines <- eq5dsuite:::script_from_session(session$steps, kept)
  labels <- vapply(kept, function(r) r$label, character(1L))
  at <- vapply(labels, function(l) grep(l, lines, fixed = TRUE)[1], integer(1L))
  expect_false(anyNA(at))
  expect_identical(at, sort(at))              # same order as the Results page
  # The removed one is gone.
  expect_false(any(grepl(session$results[[2L]]$label, lines, fixed = TRUE)))
})

test_that("values a user typed are quoted safely", {
  odd_file <- 'od"d name\\.csv'
  odd_dims <- c("It's mo", 'a"b', "c\\d", "pd", "ad")
  steps <- list(
    list(kind = "load", source = "file", file = odd_file,
         ext = "csv", read_args = list(sep = ";")),
    list(kind = "map", mapping = list(
      eq5d_version = "3L",
      names_eq5d = odd_dims,
      name_groupvar = "group with spaces", name_fu = NULL)))
  results <- list(list(
    label = "odd", result_type = "table",
    call = list(fn = "eq5d_profile_level_summary", type = "table",
                args = list(names_eq5d = odd_dims[1:2],
                            levels_fu = c("Pre\"op", "Post'op")))))

  lines <- eq5dsuite:::script_from_session(steps, results)

  # The real test: it is still valid R.
  exprs <- parse(text = paste(lines, collapse = "\n"))
  expect_gt(length(exprs), 0L)

  # And the values survive the round trip unchanged. Find the assignment by
  # walking the parsed expressions, not by slicing lines.
  assigned <- function(name) {
    at <- Filter(function(e)
      is.call(e) && identical(as.character(e[[1L]]), "<-") &&
        identical(as.character(e[[2L]]), name), as.list(exprs))
    expect_length(at, 1L)
    eval(at[[1L]][[3L]])
  }

  # The column names the user chose are written into the script as data, so
  # a quote or a backslash in one cannot change what the script does.
  mapped <- assigned("mapped")
  expect_identical(mapped[1:5], odd_dims)
  expect_true("group with spaces" %in% mapped)
  # And each is renamed to what the analysis functions expect.
  expect_identical(assigned("as_named")[1:5],
                   c("mo", "sc", "ua", "pd", "ad"))
  expect_identical(length(mapped), length(assigned("as_named")))
  # The file name, quote and backslash and all, is written as R source.
  expect_true(any(grepl(deparse(odd_file), lines, fixed = TRUE)))
})

