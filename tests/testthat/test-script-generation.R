test_that("running the script reproduces the app's values and results", {
  skip_unless_app()
  e <- app_env()
  session <- run_session(e)
  env <- run_script(generate(session))

  # The value columns, to the last bit.
  expect_identical(env$analysis_data$utility, session$data$utility)
  expect_identical(env$analysis_data$eq5d_uk_5L, session$data$eq5d_uk_5L)

  # Every saved result.
  objs <- eq5dsuite:::.result_object_names(session$results)
  for (i in seq_along(session$results)) {
    r <- session$results[[i]]
    got <- env[[objs[i]]]
    if (identical(r$result_type, "plot")) {
      # The app saves the ggplot object itself, so compare the data it carries
      # and the layers drawn from it.
      expect_s3_class(got$p, "ggplot")
      expect_equal(got$p$data, r$plot$data, info = r$label)
      expect_equal(length(got$p$layers), length(r$plot$layers), info = r$label)
      expect_equal(got$p$labels, r$plot$labels, info = r$label)
    } else {
      expect_equal(got, r$data, info = r$label)
      # And the formatted copy the script prints. The script formats the table
      # itself rather than calling into the package, so this is what keeps the
      # two from drifting: percentages, counts and headings must all match
      # what the app showed.
      expect_equal(env[[paste0(objs[i], "_formatted")]],
                   eq5dsuite:::eq5d_format_table(r$data), info = r$label)
    }
  }
})

